export function withHostedRoomsLocales(bundles: PluginLocaleBundles): PluginLocaleBundles {
  const rooms: Record<string, Messages> = { en, ja, zh, 'zh-hant': zhHant }

  return Object.fromEntries(
    Object.entries(bundles).map(([locale, bundle]) => [locale, { ...bundle, hostedRooms: rooms[locale] ?? en }])
  )
}

export function useHostedRoomsText() {
  const t = usePluginI18n('hermes-bots')

  return (key: keyof Messages) => t(`hostedRooms.${key}`)
}
